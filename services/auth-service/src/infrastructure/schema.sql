CREATE TABLE IF NOT EXISTS roles (
  roleid INTEGER PRIMARY KEY,
  rolename VARCHAR(50) NOT NULL UNIQUE
);
INSERT INTO roles(roleid, rolename) VALUES
  (1, 'CUSTOMER'), (2, 'ADMIN'), (3, 'SHIPMENT_STAFF')
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
  uid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  roleid INTEGER NOT NULL REFERENCES roles(roleid),
  email VARCHAR(254) UNIQUE,
  phone VARCHAR(16),
  is_demo BOOLEAN NOT NULL DEFAULT FALSE
);

-- Durable retry record, committed in the same Auth DB transaction as the User.
-- This is not a foreign key to another service's database.
CREATE TABLE IF NOT EXISTS auth_provisioning (
  uid INTEGER PRIMARY KEY REFERENCES users(uid),
  fullname VARCHAR(100) NOT NULL,
  state VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'DONE')),
  attempts INTEGER NOT NULL DEFAULT 0,
  last_error VARCHAR(500),
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS auth_provisioning_pending_idx
  ON auth_provisioning(next_attempt_at) WHERE state = 'PENDING';
